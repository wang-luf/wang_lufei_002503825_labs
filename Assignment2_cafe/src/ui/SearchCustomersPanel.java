    private void btnSearchByIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchByIdActionPerformed
        Integer id = parseInt(txtSearchId.getText(), "Customer ID"); if (id==null) return;
        model.Customer c = customerDirectory.findById(id);
        if (c == null) { msg("Not found."); fillTable(java.util.Collections.emptyList()); return; }
        fillTable(java.util.Arrays.asList(c));

        txtFirst.setText(c.getFirstName()==null?"":c.getFirstName());
        txtLast.setText(c.getLastName()==null?"":c.getLastName());
        txtContact.setText(c.getContact()==0 ? "" : String.valueOf(c.getContact()));        
    }//GEN-LAST:event_btnSearchByIdActionPerformed

    private void btnSearchByNameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchByNameActionPerformed
        String q = txtSearchName.getText()==null ? "" : txtSearchName.getText().trim().toLowerCase();
        java.util.List<model.Customer> res = new java.util.ArrayList<>();
        for (model.Customer c : customerDirectory.getAll()) {
            String full = ((c.getFirstName()==null?"":c.getFirstName()) + " " + (c.getLastName()==null?"":c.getLastName())).toLowerCase();
            if (full.contains(q)) res.add(c);
        }
        if (res.isEmpty()) msg("No matches.");
        fillTable(res);     
    }//GEN-LAST:event_btnSearchByNameActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int row = tblCustomers.getSelectedRow();
        if (row < 0) { msg("Select a row first."); return; }
        int id = Integer.parseInt(tblCustomers.getValueAt(row,0).toString());
        model.Customer c = customerDirectory.findById(id);
        if (c == null) { msg("Customer not found."); return; }

        c.setFirstName(txtFirst.getText()==null?"":txtFirst.getText().trim());
        c.setLastName(txtLast.getText()==null?"":txtLast.getText().trim());
        try { c.setContact(Long.parseLong(txtContact.getText().trim())); } catch(Exception ignore){}

        msg("Updated.");

        java.util.List<model.Customer> cur = new java.util.ArrayList<>();
        for (int r=0; r<tblCustomers.getRowCount(); r++){
            int cid = Integer.parseInt(tblCustomers.getValueAt(r,0).toString());
            model.Customer cc = customerDirectory.findById(cid);
            if (cc!=null) cur.add(cc);
        }
        fillTable(cur);     
    }//GEN-LAST:event_btnUpdateActionPerformed
    
    private void tblCustomersMouseClicked(java.awt.event.MouseEvent evt) {
        int row = tblCustomers.getSelectedRow();
        if (row < 0) return;
        Object idObj = tblCustomers.getValueAt(row, 0);
        if (idObj == null) return;
        int id = Integer.parseInt(idObj.toString());
        model.Customer c = customerDirectory.findById(id);
        if (c == null) return;
        txtFirst.setText(c.getFirstName()==null?"":c.getFirstName());
        txtLast.setText(c.getLastName()==null?"":c.getLastName());
        txtContact.setText(c.getContact()==0 ? "" : String.valueOf(c.getContact()));
    }


