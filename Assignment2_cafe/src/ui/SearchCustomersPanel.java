    private void fillTable(java.util.List<model.Customer> list){
        DefaultTableModel m = (DefaultTableModel) tblCustomers.getModel();
        m.setRowCount(0);
        if (list == null) return;
        for (model.Customer c : list) {
            String full = (c.getFirstName()==null?"":c.getFirstName()) + " " + (c.getLastName()==null?"":c.getLastName());
            int orders = (c.getOrders()==null) ? 0 : c.getOrders().size();
            m.addRow(new Object[]{ c.getCustomerId(), full.trim(), c.getContact(), orders });
        }
    }

