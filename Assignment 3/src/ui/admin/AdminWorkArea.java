    private void refreshBranches() {
        branchTableModel.setData(system.getBranches());
        branchTableModel.fireTableDataChanged();
    }

    private void refreshUsers() {
        userTableModel.setData(system.getUserAccounts());
        userTableModel.fireTableDataChanged();
    }

    private void refreshManagedBranchCombo() {
        branchListForCombo.clear();
        javax.swing.DefaultComboBoxModel<String> model = new javax.swing.DefaultComboBoxModel<>();
        for (Branch b : system.getBranches()) {
            branchListForCombo.add(b);        
            model.addElement(b.getName());       
        }
        jComboBox3.setModel(model);            
    }


    private void toggleManagerFields() {
        String roleStr = (String) jComboBox2.getSelectedItem();
        boolean isMgr = "BRANCH_MANAGER".equals(roleStr);
        jComboBox3.setEnabled(isMgr); 
        jSpinner1.setEnabled(isMgr);   
        jSpinner3.setEnabled(isMgr);   
    }
    

    private static class BranchTableModel extends javax.swing.table.AbstractTableModel {
        private java.util.List<model.Branch> data;
        private final String[] cols = {"ID","Name","Library ID","Building No"};

        BranchTableModel(java.util.List<model.Branch> data){ this.data = data; }
        void setData(java.util.List<model.Branch> d){ this.data = d; }
        model.Branch getAt(int r){ return data.get(r); }

        @Override public int getRowCount(){ return data==null?0:data.size(); }
        @Override public int getColumnCount(){ return cols.length; }
        @Override public String getColumnName(int c){ return cols[c]; }
        @Override public Object getValueAt(int r, int c){
            model.Branch b = data.get(r);
            return switch (c) {
                case 0 -> b.getId();
                case 1 -> b.getName();
                case 2 -> b.getLibrary().getId();
                case 3 -> b.getLibrary().getBuildingNo();
                default -> "";
            };
        }
    }


    private static class UserTableModel extends javax.swing.table.AbstractTableModel {
        private java.util.List<model.UserAccount> data;
        private final String[] cols = {"ID","Username","Display Name","Role","Managed Branch","EmpID","Exp(yrs)"};

        UserTableModel(java.util.List<model.UserAccount> data){ this.data = data; }
        void setData(java.util.List<model.UserAccount> d){ this.data = d; }

        @Override public int getRowCount(){ return data==null?0:data.size(); }
        @Override public int getColumnCount(){ return cols.length; }
        @Override public String getColumnName(int c){ return cols[c]; }
        @Override public Object getValueAt(int r, int c){
            model.UserAccount u = data.get(r);
            return switch (c) {
                case 0 -> u.getId();
                case 1 -> u.getUsername();
                case 2 -> u.getDisplayName();
                case 3 -> u.getRole().getType();
                case 4 -> u.getManagedBranch()==null ? "-" : u.getManagedBranch().getName();
                case 5 -> u.getEmployeeId()==null ? "-" : u.getEmployeeId();
                case 6 -> u.getExperienceYears()==null ? "-" : u.getExperienceYears();
                default -> "";
            };
        }
    }



