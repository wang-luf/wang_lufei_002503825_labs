    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name = jTextField1.getText().trim();                    
        int buildingNo = ((Number) jSpinner2.getValue()).intValue();    

        if (name.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Branch name is required.");
            return;
        }

        system.createBranch(name, buildingNo);

        jTextField1.setText("");
        jSpinner2.setValue(100);
        refreshBranches();
        refreshManagedBranchCombo();

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row < 0) return;

        model.Branch b = branchTableModel.getAt(row);
        system.deleteBranch(b);

        refreshBranches();
        refreshManagedBranchCombo();
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed

        String username    = jTextField2.getText().trim();
        String password    = jTextField3.getText().trim();
        String displayName = jTextField4.getText().trim();

        if (username.isEmpty() || password.isEmpty() || displayName.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "All fields are required.");
            return;
        }

        String roleStr = (String) jComboBox2.getSelectedItem();
        Role.Type type = Role.Type.valueOf(roleStr);  // "SYSTEM_ADMIN" -> Role.Type.SYSTEM_ADMIN

        Role role = switch (type) {
            case SYSTEM_ADMIN   -> new Role.SystemAdminRole();
            case BRANCH_MANAGER -> new Role.BranchManagerRole();
            case CUSTOMER       -> new Role.CustomerRole();
        };

        UserAccount ua = system.createUser(username, password, displayName, role);

        if (type == Role.Type.BRANCH_MANAGER) {

            int idx = jComboBox3.getSelectedIndex();
            if (idx >= 0 && idx < branchListForCombo.size()) {
                ua.setManagedBranch(branchListForCombo.get(idx));
            }
            ua.setEmployeeId(((Number) jSpinner1.getValue()).intValue());
            ua.setExperienceYears(((Number) jSpinner3.getValue()).intValue());
        }
        userTableModel.setData(system.getUserAccounts());
        userTableModel.fireTableDataChanged();

        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jComboBox2.setSelectedIndex(0);
        toggleManagerFields();

    }//GEN-LAST:event_jButton3ActionPerformed

